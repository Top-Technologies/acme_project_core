import math

from markupsafe import Markup, escape
from odoo import api, fields, models, _
from odoo.exceptions import UserError, ValidationError

_BOQ_TOKEN = object()

BOQ_FIELDS = ('name', 'product_name', 'quantity', 'unit_rate', 'unit', 'reference', 'bill_no', 'category')
PROPOSAL_FIELDS = tuple('proposed_' + name for name in BOQ_FIELDS)


def snapshot(line, proposed=False):
    prefix = 'proposed_' if proposed else ''
    return {name: line[prefix + name] for name in BOQ_FIELDS}


class ProjectBoqRevision(models.Model):
    _inherit = 'project.project'

    acme_boq_state = fields.Selection([('approved', 'Approved BOQ'), ('draft', 'Editing Proposal'), ('pending', 'Awaiting Approval')], default='approved', readonly=True, copy=False, tracking=True)
    acme_boq_approver_id = fields.Many2one('res.users', string='BOQ Change Approver', domain="[('share', '=', False)]", tracking=True, copy=False)
    acme_boq_requester_id = fields.Many2one('res.users', string='BOQ Change Requested By', readonly=True, copy=False)
    acme_boq_reason = fields.Text(string='Reason for BOQ Change', copy=False)
    acme_boq_decision_note = fields.Text(string='BOQ Decision Note', copy=False)
    acme_boq_revision = fields.Integer(string='Approved BOQ Revision', readonly=True, copy=False)
    acme_boq_history_ids = fields.One2many('acme.project.boq.revision', 'project_id', string='BOQ Change History', copy=False)
    acme_boq_pending_id = fields.Many2one('acme.project.boq.revision', readonly=True, copy=False, ondelete='restrict')

    @api.constrains('acme_boq_approver_id', 'company_id')
    def _check_boq_approver(self):
        for project in self:
            approver = project.acme_boq_approver_id
            if approver and (approver.share or not approver.has_group('project.group_project_user') or project.company_id not in approver.company_ids):
                raise ValidationError(_('Choose an internal Project user with access to the project company as BOQ approver.'))

    @api.model_create_multi
    def create(self, vals_list):
        for vals in vals_list:
            if any(key in vals for key in ('acme_boq_state', 'acme_boq_requester_id', 'acme_boq_pending_id', 'acme_boq_revision', 'acme_boq_history_ids')):
                raise UserError(_('BOQ approval state and history are generated by the workflow.'))
        return super().create(vals_list)

    def write(self, vals):
        if self.env.context.get('acme_boq_token') is not _BOQ_TOKEN:
            if {'acme_boq_reason', 'acme_boq_decision_note', 'acme_boq_approver_id'}.intersection(vals):
                for project in self.sorted('id'):
                    project._acme_lock_boq()
            audit = {'acme_boq_state', 'acme_boq_requester_id', 'acme_boq_pending_id', 'acme_boq_revision', 'acme_boq_history_ids'}
            if audit.intersection(vals):
                raise UserError(_('Use the BOQ change workflow buttons.'))
            if 'acme_boq_approver_id' in vals:
                if not self.env.user.has_group('project.group_project_manager'):
                    raise UserError(_('Only a Project Manager may configure the BOQ approver.'))
                if any(p.acme_boq_state != 'approved' for p in self):
                    raise UserError(_('The approver cannot change during an open BOQ proposal.'))
            for project in self:
                if 'acme_boq_reason' in vals and (project.acme_boq_state != 'draft' or project.acme_boq_requester_id != self.env.user):
                    raise UserError(_('Only the proposal requester can edit its reason while drafting.'))
                if 'acme_boq_decision_note' in vals and (project.acme_boq_state != 'pending' or project.acme_boq_approver_id != self.env.user):
                    raise UserError(_('Only the assigned approver may enter a decision note on a pending proposal.'))
        return super().write(vals)

    def _acme_lock_boq(self):
        self.ensure_one()
        self.check_access('write')
        self.env.cr.execute('SELECT id FROM project_project WHERE id = %s FOR UPDATE', [self.id])
        self.env.invalidate_all()

    def action_acme_edit_boq(self):
        self._acme_lock_boq()
        if not self.acme_boq_initialized or self.acme_boq_state != 'approved' or not self.acme_boq_ids:
            raise UserError(_('Start a proposal from an approved project BOQ.'))
        self.with_context(acme_boq_token=_BOQ_TOKEN).write({
            'acme_boq_state': 'draft', 'acme_boq_requester_id': self.env.user.id,
            'acme_boq_reason': False, 'acme_boq_decision_note': False,
            'acme_boq_pending_id': False,
        })
        for line in self.acme_boq_ids:
            line.with_context(acme_boq_token=_BOQ_TOKEN).write({'proposed_' + key: value for key, value in snapshot(line).items()})
        self.message_post(body=_('BOQ change proposal opened. Approved BOQ and certificates remain effective until approval.'))

    def _acme_require_requester(self):
        if self.acme_boq_state != 'draft' or self.acme_boq_requester_id != self.env.user:
            raise UserError(_('Only the requester can submit or discard this draft BOQ proposal.'))

    def action_acme_discard_boq(self):
        self._acme_lock_boq()
        self._acme_require_requester()
        self.with_context(acme_boq_token=_BOQ_TOKEN).write({'acme_boq_state': 'approved', 'acme_boq_reason': False})
        self.message_post(body=_('Draft BOQ proposal discarded; approved values were not changed.'))

    def action_acme_submit_boq(self):
        self._acme_lock_boq()
        self._acme_require_requester()
        if not (self.acme_boq_reason or '').strip():
            raise UserError(_('Enter the reason for the BOQ change.'))
        approver = self.acme_boq_approver_id
        if not approver or approver == self.env.user:
            raise UserError(_('Configure a different authorized BOQ approver before submission.'))
        self._check_boq_approver()
        self.with_user(approver).check_access('write')
        changes = []
        for line in self.acme_boq_ids:
            if snapshot(line) != snapshot(line, proposed=True):
                line._acme_validate_proposal()
                changes.append({'line_id': line.id, 'before': snapshot(line), 'after': snapshot(line, proposed=True)})
        if not changes:
            raise UserError(_('There are no BOQ changes to submit.'))
        history = self.env['acme.project.boq.revision'].with_context(acme_boq_token=_BOQ_TOKEN).create({
            'project_id': self.id, 'number': max(self.acme_boq_history_ids.mapped('number'), default=0) + 1,
            'reason': self.acme_boq_reason, 'requester_id': self.env.user.id,
            'approver_id': approver.id, 'submitted_at': fields.Datetime.now(), 'changes': changes,
        })
        self.with_context(acme_boq_token=_BOQ_TOKEN).write({'acme_boq_state': 'pending', 'acme_boq_pending_id': history.id})
        activity = self.activity_schedule('mail.mail_activity_data_todo', user_id=approver.id,
                               summary=_('Review BOQ change proposal %s', history.number),
                               note=_('Review the proposed BOQ changes on this project and approve or reject them.'))
        history.with_context(acme_boq_token=_BOQ_TOKEN).write({'activity_id': activity.id})
        self.message_post(body=_('BOQ change proposal submitted for approval.'))

    def _acme_require_approver(self):
        if self.acme_boq_state != 'pending' or not self.acme_boq_pending_id or self.acme_boq_pending_id.state != 'pending':
            raise UserError(_('There is no pending BOQ proposal.'))
        history = self.acme_boq_pending_id
        if history.approver_id != self.env.user or history.requester_id == self.env.user:
            raise UserError(_('Only the assigned independent approver can decide this BOQ change.'))
        return history

    def _acme_finish_boq(self, history, state, decision_note=None):
        history.with_context(acme_boq_token=_BOQ_TOKEN).write({
            'state': state, 'decision_by_id': self.env.user.id,
            'decision_at': fields.Datetime.now(),
            'decision_note': self.acme_boq_decision_note if decision_note is None else decision_note,
        })
        vals = {'acme_boq_state': 'approved', 'acme_boq_pending_id': False}
        if state == 'approved':
            vals['acme_boq_revision'] = self.acme_boq_revision + 1
        self.with_context(acme_boq_token=_BOQ_TOKEN).write(vals)
        if history.activity_id:
            history.activity_id.action_feedback(feedback=_('BOQ proposal %s.', state))
        self.message_post(body=_('BOQ change proposal %s: %s.', history.number, state))

    def action_acme_approve_boq(self):
        self._acme_lock_boq()
        history = self._acme_require_approver()
        for change in history.changes:
            line = self.env['acme.project.boq'].browse(change['line_id']).exists()
            if not line or line.project_id != self or snapshot(line) != change['before']:
                raise UserError(_('The source BOQ changed after submission. Review a fresh proposal.'))
            if snapshot(line, proposed=True) != change['after']:
                raise UserError(_('The proposal changed after submission. Submit a fresh proposal.'))
            line._acme_validate_proposal()
        for change in history.changes:
            self.env['acme.project.boq'].browse(change['line_id']).with_context(acme_boq_token=_BOQ_TOKEN).write(change['after'])
        self._acme_finish_boq(history, 'approved')

    def action_acme_reject_boq(self):
        self._acme_lock_boq()
        history = self._acme_require_approver()
        if not (self.acme_boq_decision_note or '').strip():
            raise UserError(_('Enter a reason for rejecting the BOQ proposal.'))
        self._acme_finish_boq(history, 'rejected')

    def _acme_apply_quantity_variation(self, line, baseline, quantity, reason, requester, submitted_at, changes=None):
        return self._acme_apply_boq_variations(
            [(line, baseline, quantity, changes or {})], reason, requester, submitted_at,
        )

    def _acme_apply_boq_variations(self, updates, reason, requester, submitted_at):
        self._acme_lock_boq()
        if not self.acme_boq_initialized or self.acme_boq_state != 'approved':
            raise UserError(_('Finish the open BOQ proposal before applying this variation.'))
        changes = []
        for line, baseline, quantity, values in updates:
            if line.exists() and line.source_line_id:
                self.env.cr.execute('SELECT id FROM sale_order_line WHERE id = %s FOR UPDATE', [line.source_line_id.id])
            if not line.exists() or line.project_id != self or line._acme_variation_snapshot() != baseline:
                raise UserError(_('The source BOQ or Sales Order line changed after submission. Submit a new variation.'))
            if quantity < line.quantity:
                line._acme_check_quantity_reduction(quantity)
            before = dict(snapshot(line), selling_rate=line.selling_rate)
            changes.append({'line_id': line.id, 'before': before, 'after': dict(before, quantity=quantity, **values)})
        history = self.env['acme.project.boq.revision'].with_context(acme_boq_token=_BOQ_TOKEN).create({
            'project_id': self.id, 'number': max(self.acme_boq_history_ids.mapped('number'), default=0) + 1,
            'reason': reason, 'requester_id': requester.id, 'approver_id': self.env.uid,
            'submitted_at': submitted_at, 'changes': changes,
        })
        for line, _baseline, quantity, values in updates:
            line.with_context(acme_boq_token=_BOQ_TOKEN).write(dict(values, quantity=quantity))
        self._acme_finish_boq(history, 'approved', decision_note=_('Authorized through Approvals → Variation.'))
        return history

    def _acme_new_variation_baseline(self, source):
        self.ensure_one()
        if (not source or source.order_id != self.acme_order_id or source.order_id.state != 'sale'
                or not source.product_id or source.display_type or source.is_downpayment
                or self.acme_boq_ids.filtered(lambda item: item.source_line_id == source)):
            raise UserError(_('Select an unused product line on the confirmed contract order.'))
        return {'new_source': source.id, 'source_revision': str(source.write_date),
                'boq_revision': self.acme_boq_revision, 'boq': {'quantity': 0}, 'selling_rate': 0}

    def _acme_apply_new_line_variation(self, source, baseline, quantity, reason, requester, submitted_at, changes):
        from .boq import _IMPORT_TOKEN

        self._acme_lock_boq()
        if not self.acme_boq_initialized or self.acme_boq_state != 'approved':
            raise UserError(_('Finish the open BOQ proposal before applying this variation.'))
        self.env.cr.execute('SELECT id FROM sale_order_line WHERE id = %s FOR UPDATE', [source.id])
        if self._acme_new_variation_baseline(source) != baseline:
            raise UserError(_('The proposed order line or project BOQ changed. Submit a new variation.'))
        line = self.env['acme.project.boq'].with_context(acme_import_token=_IMPORT_TOKEN).create({
            'project_id': self.id, 'source_line_id': source.id, 'sequence': source.sequence,
            'product_name': source.product_id.display_name, 'unit': source.product_uom_id.name,
            'name': changes.get('name') or source.name, 'quantity': quantity,
            'selling_rate': changes['selling_rate'],
        })
        after = dict(snapshot(line), selling_rate=line.selling_rate)
        history = self.env['acme.project.boq.revision'].with_context(acme_boq_token=_BOQ_TOKEN).create({
            'project_id': self.id,
            'number': max(self.acme_boq_history_ids.mapped('number'), default=0) + 1,
            'reason': reason, 'requester_id': requester.id, 'approver_id': self.env.uid,
            'submitted_at': submitted_at, 'changes': [{'line_id': line.id, 'before': {}, 'after': after}],
        })
        self._acme_finish_boq(history, 'approved', decision_note=_('New contract line authorized through Approvals → Variation.'))
        return history


class BoqProposedValues(models.Model):
    _inherit = 'acme.project.boq'

    proposed_name = fields.Char(string='Proposed Description')
    proposed_product_name = fields.Char(string='Proposed Product / Specification')
    proposed_quantity = fields.Float(string='Proposed Quantity')
    proposed_unit_rate = fields.Monetary(string='Proposed Tender BOQ Rate')
    proposed_unit = fields.Char(string='Proposed Unit')
    proposed_reference = fields.Char(string='Proposed Reference')
    proposed_bill_no = fields.Char(string='Proposed Bill')
    proposed_category = fields.Char(string='Proposed Category')
    proposal_state = fields.Selection(related='project_id.acme_boq_state')

    def _acme_variation_snapshot(self):
        self.ensure_one()
        source = self.source_line_id
        return {
            'boq': snapshot(self), 'selling_rate': self.selling_rate,
            'source': source.id or False, 'source_revision': str(source.write_date or ''),
            'boq_revision': self.project_id.acme_boq_revision,
        }

    def _acme_check_quantity_reduction(self, quantity):
        self.ensure_one()
        certified = self.env['acme.project.measurement'].search([
            ('boq_id', '=', self.id), ('certificate_id.state', '=', 'certified'),
        ])
        source = self.source_line_id
        if quantity + 1e-6 < max(sum(certified.mapped('quantity')), source.qty_delivered or 0,
                                source.qty_invoiced or 0, source.qty_invoiced_posted or 0):
            raise ValidationError(_('The proposed quantity is below work already certified, delivered, or invoiced. Resolve the quantity conflict before approving.'))

    def _acme_validate_proposal(self):
        self.ensure_one()
        if not (self.proposed_name or '').strip():
            raise ValidationError(_('A BOQ description is required.'))
        if any(not math.isfinite(value) or value < 0 for value in (self.proposed_quantity, self.proposed_unit_rate)):
            raise ValidationError(_('Proposed quantity and BOQ rate must be finite nonnegative numbers.'))
        used = self.env['acme.project.measurement'].search([('boq_id', '=', self.id), ('certificate_id.state', '=', 'certified')])
        certified_quantity = sum(used.mapped('quantity'))
        if self.proposed_quantity + 1e-6 < certified_quantity:
            raise ValidationError(_('The revised BOQ quantity cannot be below the quantity already certified.'))
        if certified_quantity and self.proposed_unit != self.unit:
            raise ValidationError(_('The unit cannot change after work has been certified for this item.'))


class BoqRevisionHistory(models.Model):
    _name = 'acme.project.boq.revision'
    _description = 'Project BOQ Change Approval History'
    _order = 'number desc, id desc'
    _check_company_auto = True

    name = fields.Char(compute='_compute_name')
    project_id = fields.Many2one('project.project', required=True, ondelete='restrict', check_company=True)
    company_id = fields.Many2one(related='project_id.company_id', store=True)
    number = fields.Integer(required=True)
    reason = fields.Text(required=True)
    state = fields.Selection([('pending', 'Pending'), ('approved', 'Approved'), ('rejected', 'Rejected')], default='pending', required=True)
    requester_id = fields.Many2one('res.users', required=True)
    approver_id = fields.Many2one('res.users', required=True)
    submitted_at = fields.Datetime(required=True)
    decision_by_id = fields.Many2one('res.users')
    decision_at = fields.Datetime()
    decision_note = fields.Text()
    activity_id = fields.Many2one('mail.activity', ondelete='set null')
    changes = fields.Json(required=True)
    details_html = fields.Html(compute='_compute_details', sanitize=True)

    _unique_number = models.Constraint('UNIQUE(project_id, number)', 'A BOQ proposal number must be unique within the project.')

    @api.depends('project_id.name', 'number')
    def _compute_name(self):
        for record in self:
            record.name = '%s / BOQ Change %s' % (record.project_id.name, record.number)

    @api.depends('changes')
    def _compute_details(self):
        for record in self:
            rows = []
            for change in record.changes or []:
                for field in change['after']:
                    old, new = change['before'].get(field), change['after'].get(field)
                    if old != new:
                        rows.append(Markup('<tr><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>') % (
                            escape(change['before'].get('reference') or change['before'].get('name') or ''),
                            escape(field.replace('_', ' ').title()), escape(str(old if old is not False and old is not None else '')), escape(str(new if new is not False else ''))))
            record.details_html = Markup('<table class="table table-sm"><thead><tr><th>BOQ Item</th><th>Field</th><th>Before</th><th>Proposed / Approved</th></tr></thead><tbody>%s</tbody></table>') % Markup('').join(rows)

    @api.model_create_multi
    def create(self, vals_list):
        if self.env.context.get('acme_boq_token') is not _BOQ_TOKEN:
            raise UserError(_('BOQ approval history is created by submitting a project proposal.'))
        return super().create(vals_list)

    def write(self, vals):
        if self.env.context.get('acme_boq_token') is not _BOQ_TOKEN:
            raise UserError(_('BOQ approval history is read-only.'))
        return super().write(vals)

    def unlink(self):
        raise UserError(_('BOQ approval history cannot be deleted.'))
